function getLang() { return localStorage.getItem('sunNailLang') || 'ar'; }
function setLang(l) { localStorage.setItem('sunNailLang', l); }

function applyLang(lang) {
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  // text nodes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (T[lang][key] !== undefined) {
      if (el.getAttribute('data-i18n-html') === '1') el.innerHTML = T[lang][key];
      else el.textContent = T[lang][key];
    }
  });
  // placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (T[lang][key] !== undefined) el.setAttribute('placeholder', T[lang][key]);
  });
  // lang button label
  const btn = document.querySelector('.lang-btn');
  if (btn) btn.textContent = T[lang]['lang'];
  // update service book links text already handled by data-i18n
}

function toggleLang() {
  const cur = getLang();
  const next = cur === 'ar' ? 'en' : 'ar';
  setLang(next);
  applyLang(next);
}

/* ============ Mobile menu ============ */
function initMenu() {
  const t = document.querySelector('.menu-toggle');
  const nav = document.querySelector('.nav');
  if (!t || !nav) return;
  t.addEventListener('click', () => nav.classList.toggle('open'));
  nav.querySelectorAll('a').forEach(a => a.addEventListener('click', () => nav.classList.remove('open')));
}

/* ============ Lightbox ============ */
let lbImages = [];
let lbIndex = 0;
function initLightbox() {
  const items = document.querySelectorAll('.gallery-item img');
  if (!items.length) return;
  lbImages = Array.from(items).map(i => i.src);
  items.forEach((img, i) => {
    img.parentElement.addEventListener('click', () => openLightbox(i));
  });
  const lb = document.querySelector('.lightbox');
  if (!lb) return;
  lb.querySelector('.lightbox-close').addEventListener('click', closeLightbox);
  lb.querySelector('.lightbox-prev').addEventListener('click', () => navLightbox(-1));
  lb.querySelector('.lightbox-next').addEventListener('click', () => navLightbox(1));
  lb.addEventListener('click', (e) => { if (e.target === lb) closeLightbox(); });
  document.addEventListener('keydown', (e) => {
    if (!lb.classList.contains('open')) return;
    if (e.key === 'Escape') closeLightbox();
    if (e.key === 'ArrowLeft') navLightbox(htmlDir() === 'rtl' ? 1 : -1);
    if (e.key === 'ArrowRight') navLightbox(htmlDir() === 'rtl' ? -1 : 1);
  });
}
function htmlDir() { return document.documentElement.getAttribute('dir') || 'rtl'; }
function openLightbox(i) {
  lbIndex = i;
  const lb = document.querySelector('.lightbox');
  const img = lb.querySelector('.lightbox-img');
  img.onerror = function(){ this.onerror=null; this.src="data:image/svg+xml;utf8,%3Csvg%20xmlns='http%3A%2F%2Fwww.w3.org%2F2000%2Fsvg'%20width='400'%20height='400'%3E%3Crect%20width='100%25'%20height='100%25'%20fill='%23DDA0DD'%2F%3E%3Ctext%20x='50%25'%20y='50%25'%20font-size='60'%20text-anchor='middle'%20fill='%239C6FB0'%3E%E2%9C%BA%3C%2Ftext%3E%3C%2Fsvg%3E"; };
  img.src = lbImages[i];
  lb.querySelector('.lightbox-counter').textContent = (i+1) + ' / ' + lbImages.length;
  lb.classList.add('open');
  document.body.style.overflow = 'hidden';
}
function closeLightbox() {
  const lb = document.querySelector('.lightbox');
  lb.classList.remove('open');
  document.body.style.overflow = '';
}
function navLightbox(d) {
  lbIndex = (lbIndex + d + lbImages.length) % lbImages.length;
  const lb = document.querySelector('.lightbox');
  lb.querySelector('.lightbox-img').src = lbImages[lbIndex];
  lb.querySelector('.lightbox-counter').textContent = (lbIndex+1) + ' / ' + lbImages.length;
}

/* ============ FAQ ============ */
function initFAQ() {
  document.querySelectorAll('.faq-q').forEach(q => {
    q.addEventListener('click', () => {
      const item = q.closest('.faq-item');
      item.classList.toggle('open');
    });
  });
}

/* ============ Active nav ============ */
function setActiveNav() {
  const path = location.pathname.split('/').pop() || 'index.html';
  document.querySelectorAll('.nav a').forEach(a => {
    const href = a.getAttribute('href');
    if (href === path || (path === '' && href === 'index.html')) a.classList.add('active');
  });
}

/* ============ Image fallback ============ */
function initImgFallback() {
  document.querySelectorAll('img').forEach(img => {
    img.addEventListener('error', () => {
      const fb = document.createElement('div');
      fb.className = 'img-fallback';
      fb.textContent = '✺';
      img.replaceWith(fb);
    });
  });
}

/* ============ Boot ============ */
document.addEventListener('DOMContentLoaded', () => {
  const lang = getLang();
  applyLang(lang);
  initMenu();
  initLightbox();
  initFAQ();
  setActiveNav();
  initImgFallback();

  const lb = document.querySelector('.lang-btn');
  if (lb) lb.addEventListener('click', toggleLang);

  // book buttons with service name
  document.querySelectorAll('.book-btn[data-service]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const svc = btn.getAttribute('data-service');
      const msg = getLang() === 'ar'
        ? 'السلام عليكم، أريد حجز: ' + svc + ' ✺'
        : 'Hello, I would like to book: ' + svc + ' ✺';
      const url = 'https://wa.me/966571828519?text=' + encodeURIComponent(msg);
      window.open(url, '_blank');
    });
  });

  // hero/cta wa buttons
  document.querySelectorAll('[data-wa]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const key = btn.getAttribute('data-wa');
      const msg = T[getLang()][key] || T.ar[key];
      window.open('https://wa.me/966571828519?text=' + encodeURIComponent(msg), '_blank');
    });
  });
});
